import { Injectable } from '@nestjs/common';
import { InjectRepository } from '@nestjs/typeorm';
import { Repository } from 'typeorm';
import { Website } from '../entities/website.entity';
import { WebsiteService } from '../website/website.service';
import { BlueprintPromptService } from './blueprint-prompt.service';
import { ClaudeBackendService } from './claude-backend.service';
import { ProjectMergerService } from './project-merger.service';

@Injectable()
export class FullStackCoordinatorService {
  constructor(
    private readonly claudeBackend: ClaudeBackendService,
    private readonly blueprintPrompt: BlueprintPromptService,
    private readonly projectMerger: ProjectMergerService,
    private readonly websiteService: WebsiteService,
    @InjectRepository(Website) private readonly websiteRepository: Repository<Website>,
  ) {}

  async generate(userId: string, prompt: string, requestedName?: string): Promise<Website> {
    const websiteName = requestedName?.trim() || `Full-stack app ${Date.now()}`;

    // Claude owns the shared contract and the small Node backend. v0 receives only the derived UI task.
    const claudePlan = await this.claudeBackend.generate(prompt, websiteName);
    const frontendPrompt = this.blueprintPrompt.createFrontendPrompt(prompt, claudePlan.blueprint);
    const project = this.projectMerger.merge(claudePlan, frontendPrompt);

    const generated = await this.websiteService.generateWebsite(
      userId,
      project.frontendPrompt,
      websiteName,
      'react',
      undefined,
      prompt,
    );

    const website = await this.websiteRepository.findOne({ where: { _id: generated.id } as any });
    if (!website) throw new Error('Generated website could not be reloaded for full-stack merge');
    website.prompt = prompt;
    website.fullStackBlueprint = project.blueprint;
    website.backendFiles = project.backendFiles;
    website.backendStatus = 'generated';
    website.backendLogs = 'Backend generated by Claude. Runtime has not been started yet.';
    const saved = await this.websiteRepository.save(website);
    // The original React build can be queued before backend files are attached. Queue a fresh build so the
    // R2 artifact receives its project-specific Render API gateway configuration.
    await this.websiteService.rebuildReactPreview(saved.id.toString(), userId);
    return (await this.websiteRepository.findOne({ where: { _id: saved.id } as any })) || saved;
  }
}
